import assert from 'node:assert/strict';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { randomUUID } from 'node:crypto';
import { Referee } from '../server/referee.ts';
import { createWorld, step } from '../src/sim/world.ts';
import { packInput, unpackInput } from '../src/sim/input.ts';
import { bot } from '../src/dev/bot.ts';
import { SkillInputBuffer } from '../src/ui/skill-input.ts';
import { canPayNative, nativeGasReserve, MINT_PRICE_YOCTO } from '../src/shared/market.ts';
const gas = nativeGasReserve('100000000');
assert.equal(gas, 15000000000000000000000n);
const required = BigInt(MINT_PRICE_YOCTO) + gas;
assert.equal(canPayNative({nativeBalanceYocto:String(required),nativeGasReserveYocto:String(gas)},MINT_PRICE_YOCTO),true,'exact deposit plus gas is enough, below the old arbitrary minimum');
assert.equal(canPayNative({nativeBalanceYocto:String(required-1n),nativeGasReserveYocto:String(gas)},MINT_PRICE_YOCTO),false,'one yocto below required must be rejected without number rounding');
assert.equal(canPayNative({nativeBalanceYocto:String(required)},MINT_PRICE_YOCTO),false,'missing gas quote cannot enable a payment');
const directory=mkdtempSync(join(tmpdir(),'contrapasso-chain-regression-'));
try {
 let now=Date.UTC(2026,10,13,12),ref=new Referee({directory,now:()=>now,seed:()=>42,roll:()=>0});
 const owner=ref.createSession().owner,id=ref.profile(owner).id;
 for(const event of ref.pendingChainOperations())ref.acknowledgeChain(event.id,{});
 ref.adoptChain(id,{...ref.profile(owner),coins:100,earnedToday:300,day:Math.floor(now/86400000)-1,revision:1});
 assert.equal(ref.profile(owner).earnedToday,0,'yesterday’s on-chain cap cannot suppress today’s award');
 const intent=randomUUID(),upgrade=ref.upgrade(owner,'weapon',intent),coins=ref.profile(owner).coins;
 ref=new Referee({directory,now:()=>now,seed:()=>42,roll:()=>99});
 assert.deepEqual(ref.upgrade(owner,'weapon',intent),upgrade,'intent and result survive process restart');
 assert.equal(ref.profile(owner).coins,coins,'retry never charges twice');
 assert.throws(()=>ref.upgrade(owner,'armor',intent),/different choices/);
 for(const event of ref.pendingChainOperations())ref.acknowledgeChain(event.id,{});
 const run=ref.begin(owner),equipped=ref.profile(owner).equipped!;
 ref.adoptChain(id,{...ref.profile(owner),equipped:{...equipped,weapon:'another-nft'},day:Math.floor(now/86400000),revision:2});
 assert.throws(()=>ref.submit(owner,run.id,[0]),/NFTs changed/,'kills cannot land on another weapon');
 ref.adoptChain(id,{...ref.profile(owner),equipped,day:Math.floor(now/86400000),revision:3});
 const w=createWorld(run.seed,run.skills,run.equipment),inputs:number[]=[];
 while(!['dead','won'].includes(w.phase)){const packed=packInput(bot(w));inputs.push(packed);step(w,unpackInput(packed));w.events.length=0;}
 const beforeSave=ref.profile(owner);
 now+=Math.ceil(w.tick*1000/60);ref.submit(owner,run.id,inputs);
 const saveEvent=ref.pendingChainOperations().find(e=>e.operation==='solo')!;
 assert.deepEqual(saveEvent.data.gearIds,equipped,'queued save retains the original NFT binding');
 ref.rejectChainOperation(saveEvent.id,{[id]:{...beforeSave,day:Math.floor(now/86400000),revision:4}},'Equipped NFTs changed before save');
 assert.equal(ref.profile(owner).coins,beforeSave.coins,'rejected save restores confirmed coin');
 assert.throws(()=>ref.submit(owner,run.id,inputs),/NFTs changed/,'rejected receipt cannot be displayed as a confirmed award');
 for(const event of ref.pendingChainOperations())ref.acknowledgeChain(event.id,{});
 const profile=ref.profile(owner);ref.adoptChain(id,{...profile,build:{...profile.build,weaponId:'vesper-reed'},equipped:{...equipped,weapon:'owned-staff'},day:Math.floor(now/86400000),revision:4});
 const retry=ref.begin(owner,run.id);assert.equal(retry.seed,run.seed);assert.equal(retry.equipment.weaponId,'vesper-reed','same seed uses current authenticated gear');
 const airborne=createWorld(44,['sword-1']);airborne.player.jumpT=.2;
 const buffer=new SkillInputBuffer();buffer.press(1);assert.deepEqual(buffer.take(airborne.player,false),{},'airborne input is not consumed before it is legal');
 buffer.clear();assert.deepEqual(buffer.take(airborne.player,false),{});
 console.log('Chain regressions: PASS (UTC cap reset, durable one-charge upgrade, NFT run binding, owned retry loadout, airborne skill input)');
} finally {rmSync(directory,{recursive:true,force:true});}
